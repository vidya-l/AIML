train.hist(figsize=(15,15))
plt.show()

sns.countplot(data=train, x="is_promoted")
plt.show()

num_cols = train.select_dtypes("number")
for col in num_cols:
  sns.boxplot(train[col])
  plt.title(col)
  plt.show()

train.select_dtypes("object")

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
cat_cols = ["department",	"education",	"gender"]
num_cols = ["no_of_trainings",	"age",	"previous_year_rating",
            "length_of_service",	"KPIs_met >80%",	"awards_won?",
            	"avg_training_score"]

preprocessor = ColumnTransformer(
    transformers=[
        ("num", StandardScaler(), num_cols),
        ("cat", OneHotEncoder(), cat_cols)
    ]
)

from sklearn.pipeline import Pipeline
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression

pipe = Pipeline([
    ("preprocessor", preprocessor),
    ("model", RandomForestClassifier(
        n_estimators=100,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    ))
])

X_train = train.drop("is_promoted", axis=1)
y_train = train["is_promoted"]

X_test = test.copy()

X_train = X_train.drop(["employee_id", "region","recruitment_channel"], axis=1)
X_test = X_test.drop(['recruitment_channel', "region"], axis=1)

y_train

y_train.value_counts()

print(X_train.columns.tolist())

pipe.fit(X_train, y_train)

predictions = pipe.predict(X_train)
predictions

from sklearn.metrics import accuracy_score
accuracy = accuracy_score(y_train, predictions)

print("Train Accuracy:", accuracy)

from sklearn.metrics import classification_report
print(classification_report(y_train, predictions))

#predict test data
predictions = pipe.predict(X_test)
predictions

submission = pd.DataFrame({
    "employee_id": test["employee_id"],
    "is_promoted": predictions
})

submission.to_csv("submission.csv", index=False)

