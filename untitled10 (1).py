import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
train = pd.read_csv('/content/train_LZdllcl.csv')
test = pd.read_csv('/content/test_2umaH9m (1).csv')
train.head()

test.head(2)

train.info()

test.info()

train.describe()

test.describe()

train.isna().sum()

train[train["education"].isna() == True]

train["education"].fillna(train["education"].mode()[0], inplace=True)
test["education"].fillna(test["education"].mode()[0], inplace=True)

train["previous_year_rating"].fillna(train["previous_year_rating"].median(), inplace=True)
test["previous_year_rating"].fillna(test["previous_year_rating"].median(), inplace=True)

train.info()

